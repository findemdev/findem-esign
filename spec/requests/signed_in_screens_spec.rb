# frozen_string_literal: true

# A tenant's administrator on the shared multi-tenant instance: the screens they reach once signed in name the product
# they use, with no upstream name, upgrade offer, console or community link.
describe 'Signed-in screens', :multitenant do
  let(:locale) { 'en-US' }
  let(:account) { create(:account, locale:) }
  let(:user) { create(:user, account:) }
  let(:template) { create(:template, account:, author: user) }
  let(:submission) { create(:submission, :with_submitters, template:, created_by_user: user) }
  let(:submitter) { submission.submitters.first.tap { |e| e.update!(phone: '+14155550123') } }

  let(:paths) do
    ['/', "/templates/#{template.id}", "/templates/#{template.id}/edit", "/templates/#{template.id}/code_modal",
     "/templates/#{template.id}/preferences", "/templates/#{template.id}/submissions/new",
     "/submissions/#{submission.id}", "/submitters/#{submitter.id}/edit", '/settings/profile', '/settings/account',
     '/settings/account?tour=true', '/settings/email', '/settings/notifications', '/settings/esign',
     '/settings/personalization', '/settings/users', '/users/new', "/users/#{user.id}/edit", '/settings/webhooks',
     '/settings/sso']
  end

  before do
    Accounts.create_initial_configs(account)

    sign_in(user)
  end

  %w[en-US de-DE].each do |lang|
    context "with the account in #{lang}" do
      let(:locale) { lang }

      it 'names no upstream product and links to no upstream offer' do
        paths.each do |path|
          get path

          expect(response).to have_http_status(:ok), path

          body = response.body.gsub('data-theme="docuseal"', '')

          expect(body).not_to match(/docuseal/i), path
          expect(body).not_to include('/console_redirect', 'discord.gg', Docuseal::CHATGPT_URL), path
        end
      end

      it 'points help to Findem support and keeps the source link' do
        get '/settings/account?tour=true'

        expect(response.body).to include("#{I18n.t('need_help_ask_a_question_', locale:)} #{Docuseal::SUPPORT_EMAIL}")
        expect(response.body).to include("mailto:#{Docuseal::SUPPORT_EMAIL}", Docuseal::SOURCE_URL)
      end
    end
  end

  it 'lists the generated signing certificate under the product name' do
    get '/settings/esign'

    expect(response.body).to include("#{Docuseal.product_name} Autogenerated")
  end

  it 'sends the console and upgrade routes home without a console token' do
    %w[/upgrade /manage /console_redirect].each do |path|
      get path

      expect(response).to redirect_to(root_path)
    end
  end
end
